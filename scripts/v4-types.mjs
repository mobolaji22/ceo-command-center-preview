// The types of what v4 publishes as JSON Schema come from v4 (dev-playbook-v4 ADR-0049 decision 5, ADR-0053): v4 generates each
// schema from its contracts, and this writes the TypeScript types the Command Center uses from it. There is no second definition of
// either document here; a field v4 adds or removes reaches the screens only through these files.
//   - the design document (SddDocument), which the Workshop edits;
//   - the Brand book and the Market report (Deliverable), which the Brand and Market rooms and the client's Library lay out.
//
//   npm run v4:types             copy v4's schemas (V4_DIR, default ../dev-playbook-v4) and write the types from them
//   npm run v4:types -- --check  fail if the types differ from the copied schemas, or a copy from v4's when a checkout is present
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { compile } from "json-schema-to-typescript";

const root = join(import.meta.dirname, "..");
const v4 = resolve(process.env["V4_DIR"] ?? join(root, "..", "dev-playbook-v4"));
const GENERATED = [
  { name: "SddDocument", schema: "src/lib/design/sdd-document.schema.json", types: "src/lib/design/sdd.generated.ts", v4: "packages/contracts/schemas/sdd-document.schema.json" },
  { name: "Deliverable", schema: "src/lib/deliverables/deliverables.schema.json", types: "src/lib/deliverables/deliverables.generated.ts", v4: "packages/contracts/schemas/deliverables.schema.json" },
];
const check = process.argv.includes("--check");

const typesFrom = async (g, schemaText) => {
  const schema = JSON.parse(schemaText);
  const bannerComment = `/* Generated by scripts/v4-types.mjs from ${g.schema}, which is v4's published ${g.name} schema. Do not edit: run npm run v4:types. */`;
  // The generator names the root type from its title; the id is v4's and is kept in the copied schema.
  return compile({ ...schema, $id: undefined }, g.name, { bannerComment, additionalProperties: false, strictIndexSignatures: true, maxItems: -1, format: true, style: { printWidth: 140 } });
};

const problems = [];
let compared = 0;
for (const g of GENERATED) {
  const fromV4 = join(v4, g.v4);
  if (check) {
    const copied = readFileSync(join(root, g.schema), "utf8");
    if (existsSync(fromV4)) { compared++; if (readFileSync(fromV4, "utf8") !== copied) problems.push(`${g.schema} differs from v4's (${fromV4})`); }
    if ((await typesFrom(g, copied)) !== readFileSync(join(root, g.types), "utf8")) problems.push(`${g.types} differs from what ${g.schema} gives`);
  } else {
    if (!existsSync(fromV4)) { console.error(`v4:types: v4's schema is not at ${fromV4}; set V4_DIR to a dev-playbook-v4 checkout`); process.exit(1); }
    const text = readFileSync(fromV4, "utf8");
    writeFileSync(join(root, g.schema), text);
    writeFileSync(join(root, g.types), await typesFrom(g, text));
    console.log(`wrote ${g.schema} and ${g.types}`);
  }
}
if (check) {
  if (problems.length) {
    console.error(`v4:types stale:\n  ${problems.join("\n  ")}\nRun: npm run v4:types`);
    process.exit(1);
  }
  console.log(`v4:types ok${compared === GENERATED.length ? "" : " (no v4 checkout for some, so those types were checked only against their copy)"}`);
}
