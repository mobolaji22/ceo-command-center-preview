// The design document's types come from v4 (dev-playbook-v4 ADR-0049 decision 5): v4 publishes the JSON Schema of its SddDocument,
// generated from its contracts, and this writes the TypeScript types the Workshop uses from that schema. There is no second
// definition of the document here; a field v4 adds or removes reaches the Workshop only through this file.
//
//   npm run sdd:types            copy v4's schema (V4_DIR, default ../dev-playbook-v4) and write the types from it
//   npm run sdd:types -- --check fail if the types differ from the copied schema, or the copy from v4's when a checkout is present
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { compile } from "json-schema-to-typescript";

const root = join(import.meta.dirname, "..");
const SCHEMA = "src/lib/design/sdd-document.schema.json";
const TYPES = "src/lib/design/sdd.generated.ts";
const V4_SCHEMA = join(resolve(process.env["V4_DIR"] ?? join(root, "..", "dev-playbook-v4")), "packages/contracts/schemas/sdd-document.schema.json");
const check = process.argv.includes("--check");

const banner = `/* Generated by scripts/sdd-types.mjs from ${SCHEMA}, which is v4's published SddDocument schema. Do not edit: run npm run sdd:types. */`;
const typesFrom = async (schemaText) => {
  const schema = JSON.parse(schemaText);
  // The generator names the root type from its title; the id is v4's and is kept in the copied schema.
  return compile({ ...schema, $id: undefined }, "SddDocument", { bannerComment: banner, additionalProperties: false, strictIndexSignatures: true, maxItems: -1, format: true, style: { printWidth: 140 } });
};

const problems = [];
if (check) {
  const copied = readFileSync(join(root, SCHEMA), "utf8");
  if (existsSync(V4_SCHEMA) && readFileSync(V4_SCHEMA, "utf8") !== copied) problems.push(`${SCHEMA} differs from v4's (${V4_SCHEMA})`);
  if ((await typesFrom(copied)) !== readFileSync(join(root, TYPES), "utf8")) problems.push(`${TYPES} differs from what ${SCHEMA} gives`);
  if (problems.length) {
    console.error(`sdd:types stale:\n  ${problems.join("\n  ")}\nRun: npm run sdd:types`);
    process.exit(1);
  }
  console.log(`sdd:types ok${existsSync(V4_SCHEMA) ? "" : " (no v4 checkout here, so only the types were checked against the copy)"}`);
} else {
  if (!existsSync(V4_SCHEMA)) { console.error(`sdd:types: v4's schema is not at ${V4_SCHEMA}; set V4_DIR to a dev-playbook-v4 checkout`); process.exit(1); }
  const text = readFileSync(V4_SCHEMA, "utf8");
  writeFileSync(join(root, SCHEMA), text);
  writeFileSync(join(root, TYPES), await typesFrom(text));
  console.log(`wrote ${SCHEMA} and ${TYPES}`);
}
